"""Read the dashboard's design tokens and write docs/brand/tokens.md from them.

Usage:
    python3 scripts/brand_tokens.py           # write docs/brand/tokens.md
    python3 scripts/brand_tokens.py --check   # fail when it is out of date

`frontend/src/ui/tokens.css` is the single source of the brand: its first `:root`
block holds the light theme, and `:root[data-theme="dark"]` the tokens the dark
theme changes. Every asset generator (this table, the diagrams, the social preview)
reads that file, so a product change flows into the next regeneration. Standard
library only.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS_CSS = ROOT / "frontend" / "src" / "ui" / "tokens.css"
TOKENS_MD = ROOT / "docs" / "brand" / "tokens.md"
HEX = re.compile(r"#[0-9a-fA-F]{3,8}\b")
DECLARATION = re.compile(r"--([\w-]+)\s*:\s*([^;]+);")
SECTION = re.compile(r"/\*\s*([^*]+?)(?::[^*]*)?\s*\*/")


def _block(css, selector):
    """The body of the first rule whose selector is exactly ``selector``."""
    start = css.index(selector + " {") + len(selector) + 2
    depth, end = 1, start
    while depth:
        depth += {"{": 1, "}": -1}.get(css[end], 0)
        end += 1
    return css[start : end - 1]


def _declarations(body):
    """The custom properties of a rule body, in order, with their section heading."""
    tokens, section = [], ""
    for match in re.finditer(rf"{SECTION.pattern}|{DECLARATION.pattern}", body):
        if match.group(1):
            # A heading is a short comment ("Surfaces", "Space: a 4px grid");
            # a longer one explains the token after it.
            if len(match.group(1).split()) <= 3:
                section = match.group(1).strip()
        else:
            tokens.append((section, match.group(2), " ".join(match.group(3).split())))
    return tokens


def read_tokens(path=TOKENS_CSS):
    """Every token as ``(section, name, light, dark)``; ``dark`` is None when unchanged."""
    css = path.read_text()
    light = _declarations(_block(css, ":root"))
    dark = {
        name: value for _, name, value in _declarations(_block(css, ':root[data-theme="dark"]'))
    }
    return [(section, name, value, dark.get(name)) for section, name, value in light]


def theme(name, path=TOKENS_CSS):
    """The tokens of one theme ("light" or "dark") as ``{name: value}``."""
    return {
        token: (dark if name == "dark" and dark is not None else light)
        for _, token, light, dark in read_tokens(path)
    }


def colours(path=TOKENS_CSS):
    """Every hex color the tokens define, in either theme, lower case."""
    return {value.lower() for value in HEX.findall(path.read_text())}


def render(path=TOKENS_CSS):
    """The Markdown table of the tokens of both themes."""
    lines = [
        "# Design tokens",
        "",
        (
            "<!-- Generated by scripts/brand_tokens.py from frontend/src/ui/tokens.css."
            " Do not edit; run `python3 scripts/brand_tokens.py`. -->"
        ),
        "",
        (
            "The dashboard's tokens, as `frontend/src/ui/tokens.css` defines them. Every brand"
            " asset takes its colors, type, spacing and radii from that file. *Same* means the"
            " dark theme keeps the light value."
        ),
    ]
    current = None
    for section, name, light, dark in read_tokens(path):
        if section != current:
            current = section
            lines += ["", f"## {section}", "", "| Token | Light | Dark |", "| --- | --- | --- |"]
        shown = "Same" if dark is None or dark == light else f"`{dark}`"
        lines.append(f"| `--{name}` | `{light}` | {shown} |")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when tokens.md is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not TOKENS_MD.exists() or TOKENS_MD.read_text() != text:
            print("docs/brand/tokens.md is out of date: run python3 scripts/brand_tokens.py")
            return 1
        return 0
    TOKENS_MD.parent.mkdir(parents=True, exist_ok=True)
    TOKENS_MD.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
