"""REST routes and MCP tools, one module per area, bound to the shared services.

Each area module declares its operations (``OPERATIONS``), and may declare
transport exemptions (``EXEMPTIONS``) and hand-registered MCP resources or
prompts (``SURFACES``). ``catalog`` collects them for the operation inventory
and the interface tests.
"""

import json
from pathlib import Path

from . import (
    activity,
    agent_requests,
    career,
    core,
    discovery,
    documents,
    insights,
    outcomes,
    policy,
    skills,
    source_yield,
    system,
)
from .registry import REMOVAL, alias_rows, inventory, legacy_rows

AREAS = (
    system,
    core,
    skills,
    career,
    documents,
    discovery,
    activity,
    agent_requests,
    policy,
    outcomes,
    insights,
    source_yield,
)
NOTES = Path(__file__).with_name("inventory-notes.json")
# The upgrade guide holds the tables of renamed tools and deprecated arguments
# between these markers; scripts/inventory.py writes them.
TABLES = ("<!-- names:start -->", "<!-- names:end -->")
GUIDE_PATH = "docs/user/upgrading-0.22.md"


def catalog():
    """Every declared operation, exemption and surface, by area in registration order."""
    operations, exemptions, surfaces = [], [], []
    for area in AREAS:
        operations.extend(area.OPERATIONS)
        exemptions.extend(getattr(area, "EXEMPTIONS", ()))
        surfaces.extend(getattr(area, "SURFACES", ()))
    return operations, exemptions, surfaces


def inventory_document():
    """The operation inventory generated from the declarations and their remarks."""
    operations, exemptions, _ = catalog()
    return inventory(operations, exemptions, json.loads(NOTES.read_text()))


def inventory_text():
    return json.dumps(inventory_document(), indent=2) + "\n"


def upgrade_tables():
    """The upgrade guide's tables of earlier tool names and deprecated flat arguments."""
    operations, _, _ = catalog()
    lines = [
        TABLES[0],
        "<!-- Generated by `scripts/inventory.py` from the declarations; do not edit. -->",
        "",
        f"| Before 0.22 | From 0.22 | The old name, until {REMOVAL}, takes |",
        "|---|---|---|",
    ]
    lines += [
        f"| `{old}` | `{new}` | {arguments} |" for old, new, arguments in alias_rows(operations)
    ]
    lines += [
        "",
        f"| Tool | Also accepts beside `value`, deprecated until {REMOVAL} |",
        "|---|---|",
    ]
    lines += [
        f"| `{name}` | {', '.join(f'`{field}`' for field in fields)} |"
        for name, fields in legacy_rows(operations)
    ]
    lines.append(TABLES[1])
    return "\n".join(lines)


def with_upgrade_tables(text):
    """The upgrade guide with its generated tables replaced by the current ones."""
    start, end = text.index(TABLES[0]), text.index(TABLES[1]) + len(TABLES[1])
    return text[:start] + upgrade_tables() + text[end:]
