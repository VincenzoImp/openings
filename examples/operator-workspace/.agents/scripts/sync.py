#!/usr/bin/env python3
"""Generate client adapters from the canonical agent files.

Sources: AGENTS.md, .agents/skills/ and .agents/mcp.json. Each adapter only
points to them or translates the MCP definition into a client's own format.

Usage:
  python3 .agents/scripts/sync.py --url https://openings.example   # set the server, write adapters
  python3 .agents/scripts/sync.py                                  # rewrite adapters
  python3 .agents/scripts/sync.py --check                          # compare
"""
from pathlib import Path
import json
import os
import re
import sys

root = Path(__file__).resolve().parents[2]
VAR = re.compile(r'\$\{(\w+)\}')
NOTE = 'Generated by .agents/scripts/sync.py from .agents/mcp.json; do not edit.'

SKILL_LINKS = {'.claude/skills': '../.agents/skills'}


def servers():
    data = json.loads((root / '.agents/mcp.json').read_text())['mcpServers']
    for name, server in data.items():
        url = server.get('url', '')
        local = re.match(r'http://(localhost|127\.0\.0\.1|\[::1\])(:\d+)?/', url)
        if server.get('type') != 'http' or not (url.startswith('https://') or local):
            raise SystemExit(f'.agents/mcp.json: {name} must use HTTPS (plain HTTP only on localhost)')
    return data


def headers(server, template):
    return {k: VAR.sub(lambda m: template.format(m[1]), v)
            for k, v in server.get('headers', {}).items()}


def as_json(data):
    return json.dumps(data, indent=2) + '\n'


def codex(data):
    lines = [f'# {NOTE}']
    for name, server in data.items():
        lines += ['', f'[mcp_servers.{name}]', f'url = "{server["url"]}"']
        env_headers = {}
        for key, value in server.get('headers', {}).items():
            bearer = re.fullmatch(r'Bearer \$\{(\w+)\}', value)
            if key == 'Authorization' and bearer:
                lines.append(f'bearer_token_env_var = "{bearer[1]}"')
            elif VAR.fullmatch(value):
                env_headers[key] = VAR.fullmatch(value)[1]
            else:
                raise SystemExit(f'.agents/mcp.json: Codex cannot express header {key}')
        if env_headers:
            pairs = ', '.join(f'"{k}" = "{v}"' for k, v in env_headers.items())
            lines.append(f'env_http_headers = {{ {pairs} }}')
    return '\n'.join(lines) + '\n'


def adapters():
    data = servers()
    return {
        # Claude Code (project scope; approved once per user).
        '.mcp.json': as_json({'mcpServers': {
            n: {'type': 'http', 'url': s['url'], 'headers': headers(s, '${{{}}}')}
            for n, s in data.items()}}),
        # Codex (applies after the project is trusted).
        '.codex/config.toml': codex(data),
        # Cursor.
        '.cursor/mcp.json': as_json({'mcpServers': {
            n: {'url': s['url'], 'headers': headers(s, '${{env:{}}}')}
            for n, s in data.items()}}),
        # VS Code with GitHub Copilot.
        '.vscode/mcp.json': as_json({'servers': {
            n: {'type': 'http', 'url': s['url'], 'headers': headers(s, '${{env:{}}}')}
            for n, s in data.items()}}),
        # Gemini CLI: also load AGENTS.md as its context file.
        '.gemini/settings.json': as_json({
            'context': {'fileName': ['AGENTS.md']},
            'mcpServers': {n: {'httpUrl': s['url'], 'headers': headers(s, '${{{}}}')}
                           for n, s in data.items()}}),
        # opencode.
        'opencode.json': as_json({
            '$schema': 'https://opencode.ai/config.json',
            'mcp': {n: {'type': 'remote', 'url': s['url'], 'oauth': False,
                        'headers': headers(s, '{{env:{}}}')}
                    for n, s in data.items()}}),
    }


def check():
    """Return the differences between the repository and the generated adapters."""
    errors = []
    for path, content in adapters().items():
        file = root / path
        if not file.is_file() or file.read_text() != content:
            errors.append(f'{path}: out of date; run python3 .agents/scripts/sync.py')
    for path, target in SKILL_LINKS.items():
        link = root / path
        if not link.is_symlink() or os.readlink(link) != target:
            errors.append(f'{path}: must be a symlink to {target}; run python3 .agents/scripts/sync.py')
    return errors


def write():
    for path, content in adapters().items():
        file = root / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(content)
    for path, target in SKILL_LINKS.items():
        link = root / path
        link.parent.mkdir(parents=True, exist_ok=True)
        if link.is_symlink() or link.is_file():
            link.unlink()
        if not link.exists():
            link.symlink_to(target, target_is_directory=True)


def set_url(origin):
    """Point the openings server at <origin>/mcp/, keeping other settings."""
    path = root / '.agents/mcp.json'
    data = json.loads(path.read_text())
    data['mcpServers']['openings']['url'] = origin.rstrip('/') + '/mcp/'
    path.write_text(as_json(data))


if __name__ == '__main__':
    if sys.argv[1:2] == ['--url'] and len(sys.argv) == 3:
        set_url(sys.argv[2])
        sys.argv[1:] = []
    if sys.argv[1:] == ['--check']:
        problems = check()
        if problems:
            raise SystemExit('\n'.join(problems))
        print('PASS: client adapters match .agents')
    else:
        write()
        print(f'Wrote {len(adapters())} MCP adapters and {len(SKILL_LINKS)} skill link')
